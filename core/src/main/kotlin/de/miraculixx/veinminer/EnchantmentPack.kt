package de.miraculixx.veinminer

import de.miraculixx.veinminer.data.VeinminerEnchantSettings
import de.miraculixx.veinminer.utils.json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.add
import kotlinx.serialization.json.booleanOrNull
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.decodeFromJsonElement
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonArray
import kotlinx.serialization.json.putJsonObject
import net.minecraft.SharedConstants
import net.minecraft.server.packs.PackType
import org.slf4j.LoggerFactory
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.createParentDirectories
import kotlin.io.path.exists
import kotlin.io.path.readText
import kotlin.io.path.writeText

/**
 * Loaders inject the generated pack on world load, so changes apply after a restart/rejoin.
 */
object EnchantmentPack {
    const val SETTINGS_FILE = "enchantmentSettings.json"
    const val PACK_DIR = "enchantment-pack"
    const val ENCHANTMENT_ID = "veinminer_enchantment:veinminer"

    fun loadSettings(configDir: Path): VeinminerEnchantSettings {
        val file = configDir.resolve(SETTINGS_FILE)
        if (!file.exists()) return VeinminerEnchantSettings()
        return try {
            val raw = json.parseToJsonElement(file.readText()).jsonObject
            json.decodeFromJsonElement<VeinminerEnchantSettings>(raw).apply {
                // Legacy Paper config
                if ("supportedItems" !in raw && raw["pickaxeOnly"]?.jsonPrimitive?.booleanOrNull == true) supportedItems = "#minecraft:pickaxes"
            }
        } catch (e: Exception) {
            LoggerFactory.getLogger("Veinminer").warn("Failed to load $SETTINGS_FILE config: Reason: ${e.message}")
            VeinminerEnchantSettings()
        }
    }

    /**
     * Writes the datapack into [configDir]/[PACK_DIR] and returns its root.
     */
    @JvmStatic
    fun generate(configDir: Path): Path {
        val settings = loadSettings(configDir)
        val settingsFile = configDir.resolve(SETTINGS_FILE)
        if (!settingsFile.exists()) settingsFile.createParentDirectories().writeText(json.encodeToString(settings))

        val root = configDir.resolve(PACK_DIR).createDirectories()
        val format = SharedConstants.getCurrentVersion().packVersion(PackType.SERVER_DATA)
        root.write("pack.mcmeta", buildJsonObject {
            putJsonObject("pack") {
                put("description", "Generated by Veinminer from $SETTINGS_FILE")
                putJsonArray("min_format") { add(format.major()); add(format.minor()) }
                putJsonArray("max_format") { add(format.major()); add(format.minor()) }
            }
        })

        root.write("data/veinminer_enchantment/enchantment/veinminer.json", buildJsonObject {
            putJsonObject("description") {
                put("translate", "enchantment.veinminer_enchantment.veinminer")
                put("fallback", "Veinmine")
            }
            put("supported_items", settings.supportedItems)
            put("weight", settings.weight.coerceIn(1, 1024))
            put("max_level", settings.maxLevel.coerceIn(1, 255))
            putJsonObject("min_cost") {
                put("base", settings.minCost)
                put("per_level_above_first", settings.minCostPerLevel)
            }
            putJsonObject("max_cost") {
                put("base", settings.maxCost)
                put("per_level_above_first", settings.maxCostPerLevel)
            }
            put("anvil_cost", settings.anvilCost.coerceAtLeast(0))
            putJsonArray("slots") { add("mainhand") }
            putJsonObject("effects") {}
        })

        mapOf(
            "in_enchanting_table" to settings.inEnchantingTable,
            "tradeable" to settings.tradeable,
            "on_random_loot" to settings.lootable,
            "treasure" to settings.treasure,
        ).forEach { (tag, enabled) ->
            root.write("data/minecraft/tags/enchantment/$tag.json", buildJsonObject {
                putJsonArray("values") { if (enabled) add(ENCHANTMENT_ID) }
            })
        }
        return root
    }

    private fun Path.write(path: String, content: JsonObject) =
        resolve(path).createParentDirectories().writeText(json.encodeToString(content))
}
